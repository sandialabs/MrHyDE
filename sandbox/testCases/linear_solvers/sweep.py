#!/usr/bin/env python3
"""Sweep the decks in solvers.py over a mesh (h) or time-step (cfl) study.

    ./sweep.py {gen|run|report} [h|cfl] [deck ...] [case ...] [all] [krylov]

Arguments come in any order. See README.md.
"""

import shutil
