import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUNS = HERE / "runs"
EXE = HERE.parents[3] / "mrhyde.exe"

sys.path.insert(0, str(HERE.parents[2] / "scripts" / "data_processing"))
from parse_log import stats  # noqa: E402
from solvers import SOLVERS  # noqa: E402

NP = 4

# (tag, NX, NY, NZ, final time). Every case runs 10 steps, so dt is a tenth of
# the final time and each case costs the same 12 solves.
#
# CFL = dt / h_eff, where 1/h_eff^2 = 1/hx^2 + 1/hy^2 + 1/hz^2 and the wave
# speed is 1 because the deck sets eps = mu = 1. DIRK is implicit so this is
# not a stability limit; it measures how far the stage operator has moved from
# mass-dominated toward curl-curl-dominated. The cfl* tags were named from
# min(h) rather than h_eff, so each understates the real number by 1.22x.
STUDIES = {
    "h": [
        ("N8x8x4", 8, 8, 4, 4.0),
        ("N16x8x4", 16, 8, 4, 4.0),
        ("N24x12x6", 24, 12, 6, 4.0),
        ("N32x16x8", 32, 16, 8, 4.0),
        ("N40x20x10", 40, 20, 10, 4.0),
        ("N48x24x12", 48, 24, 12, 4.0),
        ("N56x28x14", 56, 28, 14, 4.0),
    ],
    "cfl": [
        ("cfl22", 56, 28, 14, 4.0),  # repeats N56x28x14 as a consistency check
        ("cfl8", 56, 28, 14, 1.428571),
        ("cfl4", 56, 28, 14, 0.714286),
        ("cfl2", 56, 28, 14, 0.357143),
        ("cfl1", 56, 28, 14, 0.178571),
        ("cfl0p5", 56, 28, 14, 0.089286),
    ],
}

# Belos solver name.
