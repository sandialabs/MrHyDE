def deck_dir(krylov, name, tag):
    return RUNS / krylov / name / tag


def gen(names, cases, krylov):
    for name in names:
        solver, xml = SOLVERS[name]
        for tag, nx, ny, nz, tfinal in cases:
            d = deck_dir(krylov, name, tag)
            d.mkdir(parents=True, exist_ok=True)
            (d / "input.yaml").write_text(TEMPLATE.format(
                name=name, nx=nx, ny=ny, nz=nz, np=NP, solver=solver,
                krylov=KRYLOV[krylov], final_time=tfinal))
            for x in xml:
                shutil.copy2(HERE / "xml" / x, d / x)
    print("wrote %d decks under runs/%s" % (len(names) * len(cases), krylov))


def run(names, cases, krylov):
    if not EXE.is_file():
        sys.exit("no mrhyde at %s" % EXE)
    for name in names:
        for tag, _, _, _, _ in cases:
            d = deck_dir(krylov, name, tag)
            if not (d / "input.yaml").exists():
                sys.exit("%s/%s/%s not generated; run `sweep.py gen`"
                         % (krylov, name, tag))
            with open(d / "mrhyde.log", "w") as f:
                rc = subprocess.call(["mpiexec", "-n", str(NP), str(EXE)],
                                     cwd=d, stdout=f, stderr=subprocess.STDOUT)
            print("  %-26s %-10s %s%s" % (name, tag, summarize(d / "mrhyde.log"),
                                          "" if rc == 0 else " (exit %d)" % rc),
                  flush=True)


def summarize(log):
    s = stats(log)
    if not s:
        return "no solves"
    # A diverging solve reports its last iteration, not a convergence count,
    # so report drops these to a dash rather than averaging them in.
    if s["unconv"]:
        return "%d of %d solves did not converge" % (s["unconv"], s["solves"])
    return "%d solves, mean %.2f, max %d" % (s["solves"], s["mean"], s["max"])


def table(title, names, tags, cell):
    vals = {(n, t): cell(n, t) for n in names for t in tags}
    w = max([len(n) for n in names] + [len("deck")]) + 2
    c = max([len(t) for t in tags] + [len(v) for v in vals.values()]) + 1
    print("\n%s\n" % title)
    print("%-*s" % (w, "deck") + "".join("%*s" % (c, t) for t in tags))
    print("-" * (w + c * len(tags)))
    for name in names:
        print("%-*s" % (w, name) + "".join("%*s" % (c, vals[name, t]) for t in tags))


def report(names, cases, krylov):
    tags = [c[0] for c in cases]
    data = {}
    for name in names:
        for tag in tags:
            s = stats(deck_dir(krylov, name, tag) / "mrhyde.log")
            if s and not s["unconv"]:
                data[name, tag] = s
    if not data:
        sys.exit("no results under runs/%s -- try `sweep.py run`" % krylov)

    tags = [t for t in tags if any((n, t) in data for n in names)]
    head = "%s, " + KRYLOV[krylov] + ", %d ranks" % NP

    def cell(key, fmt):
        return lambda n, t: fmt % data[n, t][key] if (n, t) in data else "-"

    table(head % "Belos iterations per solve, mean", names, tags,
          cell("mean", "%.1f"))
    table(head % "Forward solve wall time, seconds", names, tags,
          cell("fwd", "%.2f"))
    if any((n, t) not in data for n in names for t in tags):
        print("\nDash: not run, crashed, or out of iterations. See "
              "runs/%s/<deck>/<case>/mrhyde.log." % krylov)


COMMANDS = {"gen": gen, "run": run, "report": report}


def parse_args(argv):
    """-> (command, deck names, cases, krylov key)."""
    if not argv or argv[0] not in COMMANDS:
        sys.exit(__doc__)
    cmd, rest = argv[0], argv[1:]

    study = "cfl" if "cfl" in rest else "h"
    cases = STUDIES[study]
    tags = [c[0] for c in cases]

    unknown = [a for a in rest
               if a not in set(SOLVERS) | set(tags) | set(KRYLOV) | {"all", "h", "cfl"}]
    if unknown:
        sys.exit("not a deck, case, study, or Krylov solver: %s" % ", ".join(unknown))
    krylov = [a for a in rest if a in KRYLOV]
    if len(krylov) > 1:
        sys.exit("one Krylov solver at a time")

    named = [a for a in rest if a in tags]
    if "all" in rest:
        picked = tags
    elif named:
        picked = named
    elif cmd == "gen":
        picked = tags  # gen writes every case so xml/ edits leave no stale copies
    else:
        picked = DEFAULT_CASES[study]

    return (cmd,
            [a for a in rest if a in SOLVERS] or list(SOLVERS),
            [c for c in cases if c[0] in picked],
            krylov[0] if krylov else "bicgstab")


def main():
    cmd, names, cases, krylov = parse_args(sys.argv[1:])
    COMMANDS[cmd](names, cases, krylov)


if __name__ == "__main__":
    main()
